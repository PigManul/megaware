#pragma once
#include <Arduino.h>

// =====================================================================
//  AudioOut — динамик NS4168 через I2S TX: BCLK=46, LRCLK=40, DOUT=7.
//  На выход подаётся стерео-поток int16 (для моно дублируем сами).
//  46/40 — страповые пины: конфигурация происходит после старта,
//  на latch загрузки не влияет.
// =====================================================================

namespace AudioOut {
    bool begin(uint32_t sampleRateHz); // (пере)настройка под файл
    bool write(const int16_t* samples, int count); // count значений (стерео-интерлив)
    void stop();                       // тишина (драйвер остаётся установленным)
    bool active();
}
