#pragma once
#include <Arduino.h>

// =====================================================================
//  Portal — Captive Portal с СОБСТВЕННОЙ страницей владельца.
//
//  Нейтральная реализация: устройство поднимает AP, подключившийся
//  клиент по captive-detection получает выбранную страницу —
//  /portal/*.html с SD/Flash (заливаются через WebUI) или встроенную
//  заглушку. Это лендинг владельца — приветствие, инструкция, демо.
//  Фишинговых шаблонов (фейк-страницы паролей) в прошивке нет.
//
//  Ресурсы: через ResMgr забирает :80 и :53 — WebUI уходит с портов
//  и возвращается после Portal::stop(). AP поднимается автоматически.
//  Работает в фоне: Portal::loop() зовётся из главного тика.
// =====================================================================

namespace Portal {
    bool start(const String& pagePath); // "" = встроенная страница
    void stop();
    bool isRunning();
    void loop();                        // обслуживать клиентов (из главного тика)
    uint32_t hits();
    const char* pageName();             // текущая выбранная страница (для UI)
}
